// 时间（时:分，可带秒），用于概览中的最近一次变化、启动时间。
function formatClock(time: string, seconds = true): string {
  return new Date(time).toLocaleTimeString('zh-CN', { hour: '2-digit', minute: '2-digit', ...(seconds ? { second: '2-digit' } : {}), hour12: false })
}

// 今天的只写时分，更早的带上日期。
function formatDayClock(time: string): string {
  const date = new Date(time)
  const clock = formatClock(time, false)
  return date.toDateString() === new Date().toDateString()
    ? clock
    : `${date.toLocaleDateString('zh-CN', { month: 'numeric', day: 'numeric' })} ${clock}`
}

