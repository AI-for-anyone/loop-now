// Package coord keeps rebuildable coordination data in process: the busy locks of Agents (and task instances), the
// console event streams, the accumulated reply text of runs, and the forwarding of interrupt commands. The database is
// the source of truth (including the queue: runs with status='queued' are dequeued by priority and queue_seq); after a
// process restart this is empty and is rebuilt from the database.
package coord

import (
	"context"
	"sort"
	"strconv"
	"strings"
	"sync"
	"time"
)

// Keys generates prefixed key names (names of event streams, queues and so on). The prefix usually ends with a colon,
// e.g. "loopnow:".
type Keys struct{ Prefix string }

// Lock is the Agent busy lock: <prefix>agent:<id>:lock.
func (k Keys) Lock(agentID string) string { return k.agent(agentID, "lock") }

// Cmd is the channel for forwarding interrupts: <prefix>agent:<id>:cmd.
func (k Keys) Cmd(agentID string) string { return k.agent(agentID, "cmd") }

// Events is the console event stream: <prefix>agent:<id>:events.
func (k Keys) Events(agentID string) string { return k.agent(agentID, "events") }

// RunText is a run's accumulated reply text: <prefix>run:<id>:text.
func (k Keys) RunText(runID string) string { return k.Prefix + "run:" + runID + ":text" }

// Overview is the overview event stream (the run status of all Agents): <prefix>overview:events.
func (k Keys) Overview() string { return k.Prefix + "overview:events" }

// Inbox is the Inbox event stream (all Inbox messages): <prefix>inbox:events.
func (k Keys) Inbox() string { return k.Prefix + "inbox:events" }

func (k Keys) agent(agentID, suffix string) string {
	return k.Prefix + "agent:" + agentID + ":" + suffix
}

// Options configures the coordination layer; the values are validated by the config package.
type Options struct {
	Prefix       string
	StreamMaxLen int64 // maximum number of entries kept per event stream; <= 0 means no trimming
	// OverviewMaxLen is the maximum number of entries kept in the overview event stream; <= 0 means no trimming.
	OverviewMaxLen int64
	// Now is the clock, replaceable in tests; time.Now when nil.
	Now func() time.Time
}

// Coord performs coordination operations in process. All state is protected by one lock and every method is atomic
// (what Redis Lua scripts or transactions used to guarantee is guaranteed here by that one lock).
type Coord struct {
	keys Keys
	opts Options
	now  func() time.Time

	// Busy locks do not expire: they are released when the holder finishes; after the process exits they are empty, and
	// on start they are restored from the in-flight runs in the database.
	mu      sync.Mutex
	locks   map[string]string  // key: Agent ID or task instance ID; value: holder
	streams map[string]*stream // key: stream name generated by Keys
	texts   map[string]string  // key: run ID; deleted when the run ends
	subs    map[string]map[chan string]struct{}
}

// New creates the coordination layer.
func New(o Options) *Coord {
	now := o.Now
	if now == nil {
		now = time.Now
	}
	return &Coord{keys: Keys{Prefix: o.Prefix}, opts: o, now: now,
		locks: map[string]string{}, streams: map[string]*stream{}, texts: map[string]string{}, subs: map[string]map[chan string]struct{}{}}
}

// Keys returns the key name generator.
func (c *Coord) Keys() Keys { return c.keys }

// LockValue builds the lock holder value "<runID>|<instanceID>".
func LockValue(runID, instanceID string) string { return runID + "|" + instanceID }

// ---------- Busy locks ----------

// Acquire sets the lock only when it does not exist and reports whether it got it. Queued runs are judged by the
// database (see ErrQueuedRunsExist in store).
func (c *Coord) Acquire(_ context.Context, agentID, owner string) (bool, error) {
	return c.Swap(context.Background(), agentID, "", owner)
}

// Hold makes owner hold the lock: when the lock is free it is set to owner, when it is already owner nothing changes,
// and when someone else holds it it returns false without changing anything.
func (c *Coord) Hold(_ context.Context, agentID, owner string) (bool, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if v := c.locks[agentID]; v != "" && v != owner {
		return false, nil
	}
	c.locks[agentID] = owner
	return true, nil
}

// Restore sets the lock only when it does not exist; used to restore the lock from an existing in-flight run. It
// reports whether it was set.
func (c *Coord) Restore(_ context.Context, agentID, owner string) (bool, error) {
	return c.Swap(context.Background(), agentID, "", owner)
}

// Release deletes the lock after checking the holder, and reports whether it was deleted.
func (c *Coord) Release(_ context.Context, agentID, owner string) (bool, error) {
	if owner == "" {
		return false, nil
	}
	return c.Swap(context.Background(), agentID, owner, "")
}

// LockOwner returns the current value of the lock; "" when the lock does not exist.
func (c *Coord) LockOwner(_ context.Context, agentID string) (string, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.locks[agentID], nil
}

// Swap atomically changes the lock from current to next: an empty current means the lock must not exist, an empty next
// means delete the lock. When the lock is not currently current it changes nothing and returns false. When handing off
// to the next run, the caller first picks the next run from the database and then swaps the lock to it.
func (c *Coord) Swap(_ context.Context, agentID, current, next string) (bool, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.locks[agentID] != current {
		return false, nil
	}
	if next == "" {
		delete(c.locks, agentID)
	} else {
		c.locks[agentID] = next
	}
	return true, nil
}

// ---------- Event streams and reply text ----------

// Event is one entry in an event stream; its ID is used directly as the SSE event ID.
type Event struct {
	ID   string
	Type string
	Data []byte
}

// stream is one event stream: it keeps the most recent entries in increasing ID order. IDs look like
// "<milliseconds>-<sequence>" (the same as the former Redis Stream); within the same millisecond the sequence
// increases, and when the clock goes backwards the previous entry's millisecond is reused.
type stream struct {
	entries []streamEntry
	lastMs  uint64
	lastSeq uint64
	// notify is closed and replaced on every append; blocking reads wait on it.
	notify chan struct{}
}

type streamEntry struct {
	ms, seq uint64
	event   Event
}

// stream returns (creating it if needed) the event stream named key. The caller holds c.mu.
func (c *Coord) stream(key string) *stream {
	s := c.streams[key]
	if s == nil {
		s = &stream{notify: make(chan struct{})}
		c.streams[key] = s
	}
	return s
}

// add appends an event, trims the oldest entries according to maxLen, and returns the entry ID. The caller holds c.mu.
func (s *stream) add(now time.Time, maxLen int64, eventType string, data []byte) string {
	ms := uint64(now.UnixMilli())
	seq := uint64(0)
	if ms <= s.lastMs {
		ms, seq = s.lastMs, s.lastSeq+1
	}
	s.lastMs, s.lastSeq = ms, seq
	id := strconv.FormatUint(ms, 10) + "-" + strconv.FormatUint(seq, 10)
	s.entries = append(s.entries, streamEntry{ms: ms, seq: seq, event: Event{ID: id, Type: eventType, Data: append([]byte(nil), data...)}})
	if maxLen > 0 && int64(len(s.entries)) > maxLen {
		drop := len(s.entries) - int(maxLen)
		s.entries = append(s.entries[:0:0], s.entries[drop:]...)
	}
	close(s.notify)
	s.notify = make(chan struct{})
	return id
}

func (s *stream) lastID() string {
	if len(s.entries) == 0 {
		return "0-0"
	}
	return s.entries[len(s.entries)-1].event.ID
}

func (s *stream) firstID() string {
	if len(s.entries) == 0 {
		return ""
	}
	return s.entries[0].event.ID
}

// since returns the entries after afterID (exclusive), at most count of them (no limit when <= 0).
func (s *stream) since(afterID string, count int64) []Event {
	ams, aseq := parseID(afterID)
	i := sort.Search(len(s.entries), func(i int) bool {
		e := s.entries[i]
		return e.ms > ams || (e.ms == ams && e.seq > aseq)
	})
	n := len(s.entries) - i
	if count > 0 && int64(n) > count {
		n = int(count)
	}
	if n == 0 {
		return nil
	}
	out := make([]Event, n)
	for k := range n {
		out[k] = s.entries[i+k].event
	}
	return out
}

func (c *Coord) append(key string, maxLen int64, eventType string, data []byte) string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.stream(key).add(c.now(), maxLen, eventType, data)
}

// AppendEvent appends an event to the Agent's event stream (keeping the most recent StreamMaxLen entries) and returns
// the entry ID.
func (c *Coord) AppendEvent(_ context.Context, agentID, eventType string, data []byte) (string, error) {
	return c.append(c.keys.Events(agentID), c.opts.StreamMaxLen, eventType, data), nil
}

// AppendOverview appends an event to the overview event stream (keeping the most recent OverviewMaxLen entries) and
// returns the entry ID.
func (c *Coord) AppendOverview(_ context.Context, eventType string, data []byte) (string, error) {
	return c.append(c.keys.Overview(), c.opts.OverviewMaxLen, eventType, data), nil
}

func (c *Coord) lastID(key string) string {
	c.mu.Lock()
	defer c.mu.Unlock()
	if s := c.streams[key]; s != nil {
		return s.lastID()
	}
	return "0-0"
}

func (c *Coord) firstID(key string) string {
	c.mu.Lock()
	defer c.mu.Unlock()
	if s := c.streams[key]; s != nil {
		return s.firstID()
	}
	return ""
}

// OverviewLastID returns the ID of the newest entry in the overview event stream; "0-0" when it is empty.
func (c *Coord) OverviewLastID(context.Context) (string, error) {
	return c.lastID(c.keys.Overview()), nil
}

// OverviewFirstID returns the ID of the oldest entry kept in the overview event stream; "" when it is empty.
func (c *Coord) OverviewFirstID(context.Context) (string, error) {
	return c.firstID(c.keys.Overview()), nil
}

// ReadOverview reads the events after afterID (exclusive) in the overview event stream, at most count of them; same
// rules as ReadEvents.
func (c *Coord) ReadOverview(ctx context.Context, afterID string, count int64, block time.Duration) ([]Event, error) {
	return c.readStream(ctx, c.keys.Overview(), afterID, count, block)
}

// AppendInbox appends an event to the Inbox event stream (keeping the most recent StreamMaxLen entries) and returns the
