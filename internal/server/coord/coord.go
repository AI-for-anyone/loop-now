func (c *Coord) AppendInbox(_ context.Context, eventType string, data []byte) (string, error) {
	return c.append(c.keys.Inbox(), c.opts.StreamMaxLen, eventType, data), nil
}

// InboxLastID returns the ID of the newest entry in the Inbox event stream; "0-0" when it is empty.
func (c *Coord) InboxLastID(context.Context) (string, error) { return c.lastID(c.keys.Inbox()), nil }

// InboxFirstID returns the ID of the oldest entry kept in the Inbox event stream; "" when it is empty.
func (c *Coord) InboxFirstID(context.Context) (string, error) { return c.firstID(c.keys.Inbox()), nil }

// ReadInbox reads the events after afterID (exclusive) in the Inbox event stream, at most count of them; same rules as
// ReadEvents.
func (c *Coord) ReadInbox(ctx context.Context, afterID string, count int64, block time.Duration) ([]Event, error) {
	return c.readStream(ctx, c.keys.Inbox(), afterID, count, block)
}

// AppendText atomically appends delta to the run's reply text and appends an event to the Agent's event stream. It
// returns the entry ID.
func (c *Coord) AppendText(_ context.Context, agentID, runID, delta, eventType string, data []byte) (string, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.texts[runID] += delta
	return c.stream(c.keys.Events(agentID)).add(c.now(), c.opts.StreamMaxLen, eventType, data), nil
}

// Snapshot atomically reads the run's reply text ("" when runID is empty or unknown) and the ID of the newest entry in
// the Agent's event stream ("0-0" when empty), consistent with each other.
func (c *Coord) Snapshot(_ context.Context, agentID, runID string) (text, lastID string, err error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if runID != "" {
		text = c.texts[runID]
	}
	lastID = "0-0"
	if s := c.streams[c.keys.Events(agentID)]; s != nil {
		lastID = s.lastID()
	}
	return text, lastID, nil
}

// FirstEventID returns the ID of the oldest entry kept in the Agent's event stream; "" when it is empty.
func (c *Coord) FirstEventID(_ context.Context, agentID string) (string, error) {
	return c.firstID(c.keys.Events(agentID)), nil
}

// ReadEvents reads the events after afterID (exclusive), at most count of them. When block > 0 and there are no new
// events it waits at most block and returns an empty result on timeout; when block <= 0 it does not wait. When ctx ends
// it returns ctx's error.
func (c *Coord) ReadEvents(ctx context.Context, agentID, afterID string, count int64, block time.Duration) ([]Event, error) {
	return c.readStream(ctx, c.keys.Events(agentID), afterID, count, block)
}

func (c *Coord) readStream(ctx context.Context, key, afterID string, count int64, block time.Duration) ([]Event, error) {
	var timer <-chan time.Time
	if block > 0 {
		t := time.NewTimer(block)
		defer t.Stop()
		timer = t.C
	}
	for {
		c.mu.Lock()
		s := c.stream(key)
		out := s.since(afterID, count)
		wait := s.notify
		c.mu.Unlock()
		if len(out) > 0 || block <= 0 {
			return out, nil
		}
		select {
		case <-wait:
		case <-timer:
			return nil, nil
		case <-ctx.Done():
			return nil, ctx.Err()
		}
	}
}

// CompareIDs compares two event IDs ("<ms>-<seq>"; a missing sequence counts as 0) numerically, returning -1 when a <
// b, 0 when equal and 1 when a > b. Parts that cannot be parsed count as 0.
func CompareIDs(a, b string) int {
	am, as := parseID(a)
	bm, bs := parseID(b)
	switch {
	case am < bm:
		return -1
	case am > bm:
		return 1
	case as < bs:
		return -1
	case as > bs:
		return 1
	}
	return 0
}

func parseID(id string) (ms, seq uint64) {
	msPart, seqPart, _ := strings.Cut(id, "-")
	ms, _ = strconv.ParseUint(msPart, 10, 64)
	seq, _ = strconv.ParseUint(seqPart, 10, 64)
	return ms, seq
}

// RunText returns the run's accumulated reply text; "" when there is none.
func (c *Coord) RunText(_ context.Context, runID string) (string, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.texts[runID], nil
}

// DeleteRunText deletes the run's accumulated reply text.
func (c *Coord) DeleteRunText(_ context.Context, runID string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	delete(c.texts, runID)
	return nil
}

// ---------- Interrupt forwarding ----------

// PublishInterrupt sends the interrupt command (run ID) to all current subscribers of the Agent; it is dropped when
// there are no subscribers, and dropped for a subscriber whose backlog is full.
func (c *Coord) PublishInterrupt(_ context.Context, agentID, runID string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	for ch := range c.subs[agentID] {
		select {
		case ch <- runID:
		default:
		}
	}
	return nil
}

// SubscribeInterrupts subscribes to the Agent's interrupt commands and returns the run IDs received. The subscription
// is in effect when it returns, so commands published afterwards reach it, unless its backlog of 16 is full:
// PublishInterrupt then drops the command, and the driver's periodic database check still finds the interrupt. When
// ctx ends the subscription is cancelled and the channel closed.
func (c *Coord) SubscribeInterrupts(ctx context.Context, agentID string) (<-chan string, error) {
	ch := make(chan string, 16)
	c.mu.Lock()
	if c.subs[agentID] == nil {
		c.subs[agentID] = map[chan string]struct{}{}
	}
	c.subs[agentID][ch] = struct{}{}
	c.mu.Unlock()
	go func() {
		<-ctx.Done()
		c.mu.Lock()
		defer c.mu.Unlock()
		delete(c.subs[agentID], ch)
		if len(c.subs[agentID]) == 0 {
			delete(c.subs, agentID)
		}
		close(ch)
	}()
	return ch, nil
}

